def normalize_tod(tod: Optional[str]) -> str:
    """Normalize time of day string (Russian or English) to standard Russian keys."""
    if not tod:
        h = datetime.now().hour
        return 'ночь' if h < 6 else 'утро' if h < 12 else 'день' if h < 18 else 'вечер'
    t = tod.lower().strip()
    if t in ("morning", "утро"):
        return "утро"
    elif t in ("day", "день", "afternoon"):
        return "день"
    elif t in ("evening", "вечер"):
        return "вечер"
    elif t in ("night", "ночь"):
        return "ночь"
    return "утро"

def sanitize_speech(text: str) -> str:
    """Remove robotic gender artifacts and enforce clean punctuation."""
    replacements = [
        (r'заслужил\(-а\)', 'это заслуженная награда'),
        (r'заряжен\(-а\)', 'энергия на высоте'),
        (r'сделал\(-а\)', 'уже сделано более чем достаточно'),
        (r'откладывал\(-а\)', 'давно ждет своего часа'),
        (r'сломался\(-ась\)', 'нужна подзарядка'),
        (r'устал\(-а\)', 'силы на исходе'),
        (r'готов\(-а\)', 'в полной готовности'),
        (r'смог\(-ла\)', 'удалось сделать'),
        (r'\([а-яёА-ЯЁ-]+\)', ''),
    ]
    for pat, repl in replacements:
        text = re.sub(pat, repl, text, flags=re.IGNORECASE)
    # Capitalize after period and start of sentences
    text = re.sub(r'([.!?…]\s+)([а-яё])', lambda m: m.group(1) + m.group(2).upper(), text)
    if text and text[0].islower():
        text = text[0].upper() + text[1:]
    return re.sub(r'\s{2,}', ' ', text).strip()

def validate_tod_speech(text: str, tod: str) -> bool:
    """Validate that text strictly conforms to time of day rules."""
    t_lower = text.lower()
    if tod == "утро":
        banned = ["вечер", "день", "днем", "днём", "ночь", "ноч"]
        if any(b in t_lower for b in banned):
            return False
    elif tod == "день":
        banned = ["утр", "вечер", "ночь", "ноч"]
        if any(b in t_lower for b in banned):
            return False
    elif tod == "вечер":
        banned = ["утр", "день", "днем", "днём", "ночь", "ноч"]
        if any(b in t_lower for b in banned):
            return False
    elif tod == "ночь":
        banned = ["утр", "день", "днем", "днём", "вечер"]
        if any(b in t_lower for b in banned):
            return False
    return True

