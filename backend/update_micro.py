idx_start = None
idx_end = None
for i, l in enumerate(lines):
    if l.startswith('MICRO ='):
        idx_start = i
    if idx_start is not None and l.strip() == '}' and i > idx_start:
        idx_end = i
        break

if idx_start is not None and idx_end is not None:
    lines = lines[:idx_start] + new_micro_lines + lines[idx_end+1:]
    with open('backend/speeches.py', 'w', encoding='utf-8') as f:
        f.writelines(lines)
    print(f'Successfully updated MICRO! Charged: {len(new_micro_lines)}, Drained: {len(new_micro_lines)}')
else:
    print('Failed to locate MICRO block')
